/* =====================================================================
   Create the accounts the test suites sign in with, on a throwaway
   database, using freshly generated random passwords — then write them
   to .env.test (git-ignored).

   This exists so that no password that works anywhere is ever written
   into a file that gets committed. Run it once per test database:

     DATABASE_URL=postgres://…/policyhub_test node scripts/seed-test-accounts.mjs

   It refuses to run against a database that looks like production.
   ===================================================================== */
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';
import bcrypt from 'bcryptjs';
import { pool, q, initDb } from '../src/db.js';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const url = process.env.DATABASE_URL || '';

if (process.env.NODE_ENV === 'production') {
  console.error('Refusing to seed test accounts with NODE_ENV=production.');
  process.exit(1);
}
if (/prod|render\.com|amazonaws|\.internal/i.test(url) && !process.env.ALLOW_UNSAFE_SEED) {
  console.error(
    `Refusing to seed test accounts: DATABASE_URL looks like a hosted/production database.\n` +
    `Point it at a local throwaway database instead.`
  );
  process.exit(1);
}

const pw = () => crypto.randomBytes(18).toString('base64url');   // 24 chars

await initDb();

// The fixtures need entities and investors to attach to; initDb seeds LCG1/LCG2.
const { rows: funds } = await q('SELECT id, code FROM funds ORDER BY code');
const byCode = Object.fromEntries(funds.map((f) => [f.code, f.id]));

let { rows: investors } = await q('SELECT id, name FROM investors ORDER BY id LIMIT 2');
if (investors.length < 2) {
  for (const name of ['Test Investor One', 'Test Investor Two'].slice(investors.length))
    await q('INSERT INTO investors (name) VALUES ($1) ON CONFLICT DO NOTHING', [name]);
  ({ rows: investors } = await q('SELECT id, name FROM investors ORDER BY id LIMIT 2'));
}

const ACCOUNTS = [
  { key: 'ADMIN',     email: 'admin@test.local',     role: 'admin',    name: 'Test Admin' },
  { key: 'MANAGER1',  email: 'pm1@test.local',       role: 'manager',  name: 'PM One',
    funds: ['LCG1'] },
  { key: 'MANAGER2',  email: 'pm2@test.local',       role: 'manager',  name: 'PM Two',
    funds: ['LCG1', 'LCG2'] },
  { key: 'INVESTOR1', email: 'investor1@test.local', role: 'investor', name: 'Investor One',
    investor: 0 },
  { key: 'INVESTOR2', email: 'investor2@test.local', role: 'investor', name: 'Investor Two',
    investor: 1 },
];

const env = [
  '# Generated by scripts/seed-test-accounts.mjs — throwaway test credentials.',
  '# Git-ignored. Regenerate at any time; never reuse these anywhere real.',
  `TEST_BASE=${process.env.TEST_BASE || 'http://localhost:3000'}`,
  '',
];

for (const a of ACCOUNTS) {
  const password = pw();
  const hash = await bcrypt.hash(password, 12);
  const investorId = a.investor === undefined ? null : investors[a.investor]?.id ?? null;
  if (a.role === 'investor' && !investorId) {
    console.error(`Cannot create ${a.email}: no investor record to attach to.`);
    process.exit(1);
  }
  const { rows } = await q(
    `INSERT INTO users (email, password_hash, full_name, role, investor_id, is_active)
     VALUES ($1,$2,$3,$4,$5,true)
     ON CONFLICT (email) DO UPDATE
       SET password_hash = EXCLUDED.password_hash, full_name = EXCLUDED.full_name,
           role = EXCLUDED.role, investor_id = EXCLUDED.investor_id, is_active = true
     RETURNING id`,
    [a.email, hash, a.name, a.role, investorId]
  );
  const id = rows[0].id;
  await q('DELETE FROM user_funds WHERE user_id = $1', [id]);
  for (const code of a.funds || [])
    await q('INSERT INTO user_funds (user_id, fund_id) VALUES ($1,$2)', [id, byCode[code]]);

  env.push(`TEST_${a.key}_EMAIL=${a.email}`, `TEST_${a.key}_PASSWORD=${password}`);
  console.log(`  ${a.email.padEnd(24)} ${a.role}${a.funds ? ` (${a.funds.join(', ')})` : ''}`);
}

const target = path.join(root, '.env.test');
fs.writeFileSync(target, `${env.join('\n')}\n`, { mode: 0o600 });
console.log(`\nWrote ${target} (mode 600). It is git-ignored — keep it that way.`);

await pool.end();
